/**
 * Calculates summary metrics for all 6 deployment statuses.
 */
export function getElguStatusSummaries(lgus: LguRecord[] = ELGU_LGUS_DATA): ElguStatusSummary[] {
  const total = lgus.length;
  const statuses: ElguDeploymentStatus[] = ["Live", "Build UP", "UAT", "Inactive", "No System", "Own System"];

  return statuses.map((status) => {
    const subset = lgus.filter((l) => l.status === status);
    const count = subset.length;
    const percentage = total > 0 ? Math.round((count / total) * 100) : 0;
    const cfg = ELGU_STATUS_CONFIG[status];

    let keyMetric = `${count} LGUs`;
    let keyMetricLabel = "Total LGUs";

    if (status === "Live") {
      const totalTx = subset.reduce((acc, curr) => acc + curr.monthlyTransactions, 0);
      keyMetric = `${totalTx.toLocaleString()} tx/mo`;
      keyMetricLabel = "Total Tx Volume";
    } else if (status === "Build UP") {
      keyMetric = `${count} in GLP`;
      keyMetricLabel = "Go-Live Program";
    } else if (status === "UAT") {
      const v2Count = subset.filter((l) => l.versions.includes("V2 eLGU")).length;
      keyMetric = `${v2Count} on V2`;
      keyMetricLabel = "Testing V2 Suite";
    } else if (status === "Inactive") {
      keyMetric = `${count} Actions`;
      keyMetricLabel = "Intervention Req.";
    } else if (status === "No System") {
      keyMetric = `${count} Priority`;
      keyMetricLabel = "Digitization Funnel";
    } else if (status === "Own System") {
      keyMetric = `${count} Bridges`;
      keyMetricLabel = "eGovPH Gateway";
    }

    return {
      status,
      count,
      percentage,
      description: cfg.description,
      badgeColor: cfg.bgColor,
      textColor: cfg.textColor,
      borderColor: cfg.borderColor,
      bgLight: cfg.lightBg,
      accentColor: cfg.color,
      keyMetric,
      keyMetricLabel,
    };
  });
}

/**
 * Computes provincial distribution matrix for all 6 deployment statuses.
 */
export function getProvincialStatusBreakdown(lgus: LguRecord[] = ELGU_LGUS_DATA) {
  return PROVINCES_LIST.map((province) => {
    const provinceLgus = lgus.filter((l) => l.province === province);
    const total = provinceLgus.length;

    const live = provinceLgus.filter((l) => l.status === "Live").length;
    const buildUp = provinceLgus.filter((l) => l.status === "Build UP").length;
    const uat = provinceLgus.filter((l) => l.status === "UAT").length;
    const inactive = provinceLgus.filter((l) => l.status === "Inactive").length;
    const noSystem = provinceLgus.filter((l) => l.status === "No System").length;
    const ownSystem = provinceLgus.filter((l) => l.status === "Own System").length;

    // Version counts
    const v2Elgu = provinceLgus.filter((l) => l.versions.includes("V2 eLGU")).length;
    const v1Bpbc = provinceLgus.filter((l) => l.versions.includes("V1 BPBC")).length;
    const v1Bpco = provinceLgus.filter((l) => l.versions.includes("V1 BPCO")).length;

    // Readiness score
    const readinessScore =
      total > 0
        ? Math.round(
            ((live * 1.0 + ownSystem * 0.95 + uat * 0.75 + buildUp * 0.45) / total) * 100
          )
        : 0;

    return {
      province,
      total,
      live,
      buildUp,
      uat,
      inactive,
      noSystem,
      ownSystem,
      v2Elgu,
      v1Bpbc,
      v1Bpco,
      readinessScore,
    };
  });
}

